/// <summary>
/// Builds a large work directory through the Core API where it exists (projects, opening, groups, annotations) and writes
/// directly what would take hours through the import: image files with their rows (through the real insert of
/// ImagesManager, so the schema and indexes are the product's) and finished job rows. Every step is resumable.
/// A library generated before images had rows gets rows for its existing files.
/// </summary>
internal static class LibraryGenerator
{
    internal const string BaseModelId = "yolo26n";
    private const string ImagesKind = ProjectImage.ResourceKind;
    internal const string GroupName = "Perf frames";
    private const int RowBatch = 5000;
    // Images at the start of the largest group get annotations, so the annotation page of the first gallery page is real.
    private const int AnnotatedPrefix = 300;
    private const int JobBatch = 1000;

    internal static async Task RunAsync(PerfOptions options)
    {
        var watch = Stopwatch.StartNew();
        Directory.CreateDirectory(options.Root);
        EnsureWeights(options);
        var core = CoreFactory.GetInstance(new CoreOptions(options.Root, options.Catalog));
        await core.InitializeAsync();

        var manifest = PerfManifest.Load(options.Root) ?? PerfManifest.Plan(options);
        if (manifest.Files != options.Files || manifest.Largest != options.Largest || manifest.Projects.Count != options.Projects)
        {
            Console.WriteLine($"Existing plan is kept: {manifest.Projects.Count} projects, {manifest.Files} files. Delete the folder to change it.");
        }
        manifest.Jobs = Math.Max(manifest.Jobs, options.Jobs);
        manifest.Save(options.Root);

        foreach (var planned in manifest.Projects.Where(planned => planned.Id is null))
        {
            var created = await core.Projects.CreateAsync(new ProjectSettings(planned.Name, "Generated by MautVision.Perf", BaseModelId,
                new InputSize(640, 640)));
            planned.Id = created.Id;
            manifest.Save(options.Root);
        }
        Console.WriteLine($"Projects: {manifest.Projects.Count} ({watch.Elapsed.TotalSeconds:F1} s).");

        var samples = SampleImages.Create(8);
        Console.WriteLine($"Sample JPEGs: {SampleImages.Width}x{SampleImages.Height}, {string.Join(", ", samples.Select(sample => sample.Length / 1024 + " KB"))}.");
        // Real facts of the samples: file hash, size with orientation and pixel hash from one decode, as the import computes them.
        var facts = samples.Select(sample => (Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(sample)),
            ImagePixels.Decode(new MemoryStream(sample)) ?? throw new InvalidDataException("A sample JPEG does not decode."), (long)sample.Length)).ToArray();
        var written = 0L;
        foreach (var planned in manifest.Projects.Where(planned => planned.Files > 0))
        {
            written += await FillImagesAsync(core, planned, samples, facts);
        }
        Console.WriteLine($"Material files: {manifest.Files} planned, {written} written now ({watch.Elapsed.TotalSeconds:F1} s).");

        var largest = manifest.LargestProject;
        await AddJobsAsync(core, largest.Id!, manifest.Jobs);
        foreach (var planned in manifest.Projects.Where(planned => planned.Archived))
        {
            var project = await core.Projects.GetAsync(planned.Id!);
            await project.SetArchivedAsync(true);
        }

        await AnnotateAsync(core, largest.Id!);
        await ReviewAllAsync(core, largest.Id!);
        var images = await ImagesDirectoryAsync(core, largest.Id!);
        CreateBuckets(images, PerfManifest.BucketsDirectory(options.Root));
        SqliteConnection.ClearAllPools();

        var (count, bytes, allocated) = Measure(options.Root);
        Console.WriteLine($"Done in {watch.Elapsed.TotalSeconds:F1} s: {count} files, {bytes / 1048576.0:F0} MB data, "
            + $"~{allocated / 1048576.0:F0} MB on disk (4 KB clusters; bucket links share data with the flat folder).");
    }

    /// <summary>A file of the catalogue size reports the model as installed; content is verified only before use.</summary>
    private static void EnsureWeights(PerfOptions options)
    {
        using var catalog = JsonDocument.Parse(File.ReadAllText(options.Catalog));
        var size = catalog.RootElement.EnumerateArray().First(entry => entry.GetProperty("id").GetString() == BaseModelId)
            .GetProperty("byteSize").GetInt64();
        var weights = Path.Combine(options.Root, "BaseModels", "weights", BaseModelId + ".pt");
        if (File.Exists(weights) && new FileInfo(weights).Length == size) return;
        Directory.CreateDirectory(Path.GetDirectoryName(weights)!);
        using var file = File.Create(weights);
        file.SetLength(size);
    }

    private static async Task<string> ImagesDirectoryAsync(ICore core, string projectId)
    {
        var project = (Project)await core.Projects.OpenAsync(projectId);
        var files = await project.Store.GetFilesAsync();
        return files.CreateDirectory(ImagesKind);
    }

    /// <summary>
    /// Places files exactly where MaterialFiles puts them (files/images/&lt;guid&gt;.jpg) and gives every file a row in the
    /// project's "Perf frames" group, written in batches through ImagesManager.InsertImagesAsync. Files of an older library
    /// without rows get their rows first.
    /// </summary>
    private static async Task<long> FillImagesAsync(ICore core, PlannedProject planned, byte[][] samples, (string Sha, DecodedImage Image, long Size)[] facts)
    {
        var project = (Project)await core.Projects.OpenAsync(planned.Id!);
        var files = await project.Store.GetFilesAsync();
        var directory = files.CreateDirectory(ImagesKind);
        var group = (await project.Images.ListGroupsAsync()).FirstOrDefault(item => item.Name == GroupName)
            ?? await project.Images.CreateGroupAsync(GroupName, "Generated by MautVision.Perf", ImageSplitHint.Unassigned);
        var rows = await project.Store.ReadAsync(async (connection, token) =>
        {
            await using var command = connection.CreateCommand();
            command.CommandText = "SELECT id FROM images;";
            var ids = new HashSet<Guid>();
            await using var reader = await command.ExecuteReaderAsync(token);
            while (await reader.ReadAsync(token)) ids.Add(Guid.ParseExact(reader.GetString(0), "D"));
            return ids;
        });
        var existing = Directory.EnumerateFiles(directory, "*.jpg").Select(path => Guid.ParseExact(Path.GetFileNameWithoutExtension(path), "D")).ToList();
        var orphans = existing.Where(id => !rows.Contains(id)).ToArray();
        if (orphans.Length > 0)
        {
            await InsertRowsAsync(project, group.Id, orphans, rows.Count, facts);
            Console.WriteLine($"  {planned.Name}: rows for {orphans.Length} existing files.");
        }
        var missing = planned.Files - existing.Count;
        if (missing <= 0) return 0;
        var watch = Stopwatch.StartNew();
        var start = existing.Count;
        for (var batch = 0; batch < missing; batch += RowBatch)
        {
            var count = Math.Min(RowBatch, missing - batch);
            var ids = Enumerable.Range(0, count).Select(_ => Guid.NewGuid()).ToArray();
            Parallel.For(0, count, new ParallelOptions { MaxDegreeOfParallelism = Math.Min(8, Environment.ProcessorCount) }, index =>
                File.WriteAllBytes(files.GetPath(ImagesKind, ids[index], ".jpg"), samples[(start + batch + index) % samples.Length]));
            await InsertRowsAsync(project, group.Id, ids, start + batch, facts);
            if ((batch / RowBatch + 1) % 4 == 0)
            {
                Console.WriteLine($"  {planned.Name}: {start + batch + count}/{planned.Files} ({(batch + count) / watch.Elapsed.TotalSeconds:F0} files/s)");
            }
        }
        Console.WriteLine($"  {planned.Name}: {planned.Files} files ({missing} new with rows in {watch.Elapsed.TotalSeconds:F1} s).");
        return missing;
    }

    /// <summary>Rows of one batch in one transaction; the sample of a file is chosen by its position, as when it was written.</summary>
    private static Task InsertRowsAsync(Project project, Guid groupId, IReadOnlyList<Guid> ids, int position, (string Sha, DecodedImage Image, long Size)[] facts)
        => project.Store.WriteAsync(async (connection, transaction, token) =>
        {
            var images = ids.Select((id, index) =>
            {
                var number = position + index;
                var (sha, image, size) = facts[number % facts.Length];
                return new ImportedImage(id, $"frame-{number:D6}.jpg", image.Format, image.Width, image.Height, size, sha, image.PixelHash,
                    new ImageLineage(ImageLineageKind.File, "file:" + image.PixelHash));
            }).ToArray();
            var first = await ImagesManager.ReserveOrdinalsAsync(connection, transaction, groupId, images.Length, token);
            await ImagesManager.InsertImagesAsync(connection, transaction, groupId, images, first, "perf-generator", token);
            await using var counters = connection.CreateCommand();
            counters.Transaction = transaction;
            counters.CommandText = "UPDATE image_groups SET image_count = image_count + $count WHERE id = $id;";
            counters.Parameters.AddWithValue("$count", images.Length);
            counters.Parameters.AddWithValue("$id", groupId.ToString("D"));
            await counters.ExecuteNonQueryAsync(token);
        });

    /// <summary>
    /// Annotations through the real API for the first images of the largest group: every third gets two to four boxes, so
    /// the annotation page of the first gallery page reads real objects.
    /// </summary>
    private static async Task AnnotateAsync(ICore core, string projectId)
    {
        var project = await core.Projects.OpenAsync(projectId);
        var group = (await project.Images.ListGroupsAsync()).First(item => item.Name == GroupName);
        var workspace = await project.Classes.GetWorkspaceAsync();
        var owner = workspace.Classes.FirstOrDefault(item => item.Name == "Perf object") ?? await project.Classes.CreateAsync("Perf object", "");
        var page = await project.Images.ListImagesAsync(group.Id, new ImageFilter(), 200);
        var images = page.Items.Concat((await project.Images.ListImagesAsync(group.Id, new ImageFilter(), 200, page.NextCursor)).Items)
            .Take(AnnotatedPrefix).ToArray();
        var saved = 0;
        for (var index = 0; index < images.Length; index += 3)
        {
            var image = images[index];
            if (image.AnnotationRevision > 1) continue;
            var objects = Enumerable.Range(0, 2 + index % 3)
                .Select(box => new AnnotationObjectInput(null, owner.Id, null, new ImageBox(0.05 + box * 0.2, 0.1, 0.15, 0.3))).ToArray();
            await project.Images.SaveAnnotationAsync(image.Id, new AnnotationInput(objects, null, ImageReviewState.Reviewed), image.AnnotationRevision);
            saved++;
        }
        if (saved > 0) Console.WriteLine($"Annotations: {saved} saved through the API in the largest group.");
    }

    /// <summary>
    /// The dataset source of the benchmark: every remaining unreviewed image of the largest group gets a reviewed annotation
    /// revision 2 — every fourth with one or two boxes of the perf class, the rest as checked empty frames — written in batches
    /// with the schema's own tables, as SaveAnnotationAsync would store them.
    /// </summary>
    private static async Task ReviewAllAsync(ICore core, string projectId)
    {
        var project = (Project)await core.Projects.OpenAsync(projectId);
        var classId = (await project.Classes.GetWorkspaceAsync()).Classes.First(item => item.Name == "Perf object").Id.ToString("D");
        var watch = Stopwatch.StartNew();
        var total = 0;
        while (true)
        {
            var batch = await project.Store.WriteAsync(async (connection, transaction, token) =>
            {
                await using var select = connection.CreateCommand();
                select.Transaction = transaction;
                select.CommandText = "SELECT id, ordinal FROM images WHERE review_state = 'unreviewed' AND annotation_revision = 1 LIMIT 5000;";
                var rows = new List<(string Id, long Ordinal)>();
                await using (var reader = await select.ExecuteReaderAsync(token))
                {
                    while (await reader.ReadAsync(token)) rows.Add((reader.GetString(0), reader.GetInt64(1)));
                }
                if (rows.Count == 0) return 0;
                var now = DateTimeOffset.UtcNow.ToUnixTimeMilliseconds();
                await using var annotation = connection.CreateCommand();
                annotation.Transaction = transaction;
                annotation.CommandText = "INSERT INTO image_annotations (image_id, revision, review_state, object_count, created_at) VALUES ($id, 2, 'reviewed', $count, $now);";
                annotation.Parameters.AddWithValue("$now", now);
                var annotationId = annotation.Parameters.Add("$id", SqliteType.Text);
                var annotationCount = annotation.Parameters.Add("$count", SqliteType.Integer);
                await using var item = connection.CreateCommand();
                item.Transaction = transaction;
                item.CommandText = """
                    INSERT INTO image_annotation_objects (image_id, revision, position, object_id, class_id, class_variant_id, x, y, width, height)
                    VALUES ($id, 2, $position, $object, $class, NULL, $x, 0.2, 0.2, 0.3);
                    """;
                item.Parameters.AddWithValue("$class", classId);
                var itemId = item.Parameters.Add("$id", SqliteType.Text);
                var position = item.Parameters.Add("$position", SqliteType.Integer);
                var objectId = item.Parameters.Add("$object", SqliteType.Text);
                var x = item.Parameters.Add("$x", SqliteType.Real);
                await using var image = connection.CreateCommand();
                image.Transaction = transaction;
                image.CommandText = "UPDATE images SET annotation_revision = 2, review_state = 'reviewed', object_count = $count, revision = revision + 1 WHERE id = $id;";
                var imageId = image.Parameters.Add("$id", SqliteType.Text);
                var imageCount = image.Parameters.Add("$count", SqliteType.Integer);
                foreach (var (id, ordinal) in rows)
                {
                    var count = ordinal % 4 == 0 ? 1 + (int)(ordinal / 4 % 2) : 0;
                    annotationId.Value = imageId.Value = itemId.Value = id;
                    annotationCount.Value = imageCount.Value = count;
                    await annotation.ExecuteNonQueryAsync(token);
                    for (var index = 0; index < count; index++)
                    {
                        position.Value = index;
                        objectId.Value = Guid.NewGuid().ToString("D");
                        x.Value = 0.1 + index * 0.4;
                        await item.ExecuteNonQueryAsync(token);
                    }
                    await image.ExecuteNonQueryAsync(token);
                }
                return rows.Count;
            });
            if (batch == 0) break;
            total += batch;
        }
        if (total > 0) Console.WriteLine($"Reviewed annotations for the dataset benchmark: {total} images ({watch.Elapsed.TotalSeconds:F1} s).");
    }

    /// <summary>Finished job history of the largest project, written through the real jobs table SQL.</summary>
    private static async Task AddJobsAsync(ICore core, string projectId, int target)
    {
        var project = (Project)await core.Projects.OpenAsync(projectId);
        var store = project.Store;
        var existing = await store.ReadAsync(async (connection, token) =>
        {
            await using var command = connection.CreateCommand();
            command.CommandText = "SELECT count(*) FROM jobs;";
            return Convert.ToInt32(await command.ExecuteScalarAsync(token));
        });
        var random = new Random(existing);
        var start = DateTimeOffset.UtcNow.AddDays(-90);
        for (var batch = existing; batch < target; batch += JobBatch)
        {
            var size = Math.Min(JobBatch, target - batch);
            await store.WriteAsync(async (connection, transaction, token) =>
            {
                for (var index = 0; index < size; index++)
                {
                    var number = batch + index;
                    var created = start.AddMinutes(number * 12);
                    var finished = created.AddSeconds(5 + random.Next(600));
                    var status = (number % 50) switch { 0 => JobStatus.Failed, 1 => JobStatus.Cancelled, _ => JobStatus.Succeeded };
                    var total = 1 + random.Next(5000);
                    var job = new JobInfo(Guid.NewGuid(), number % 3 == 0 ? "generation.run" : "images.import", projectId,
                        "perf-" + Guid.NewGuid().ToString("N"), status, status == JobStatus.Succeeded ? 100 : random.Next(100), null,
                        status == JobStatus.Succeeded ? total : random.Next(total), total,
                        status == JobStatus.Failed ? new JobError("jobs.failed", "Generated failure.") : null,
                        status == JobStatus.Cancelled, created, finished, created.AddMilliseconds(200), finished, 4);
                    var input = JsonSerializer.Serialize(new { files = Enumerable.Range(0, 3).Select(item => $"D:/import/batch-{number}/{item}.jpg") });
                    await JobsTable.InsertAsync(connection, transaction, job, input, token);
                }
            });
        }
        Console.WriteLine($"Jobs: {target} finished rows in the largest project ({Math.Max(0, target - existing)} new).");
    }

    /// <summary>Hard links in 256 buckets (first two hex characters of the ID): the same files in the alternative layout.</summary>
    private static void CreateBuckets(string images, string buckets)
    {
        var watch = Stopwatch.StartNew();
        var created = 0;
        foreach (var file in Directory.EnumerateFiles(images, "*.jpg"))
        {
            var name = Path.GetFileName(file);
            var bucket = Path.Combine(buckets, name[..2]);
            var link = Path.Combine(bucket, name);
            if (File.Exists(link)) continue;
            Directory.CreateDirectory(bucket);
            if (!CreateHardLink(link, file, IntPtr.Zero))
            {
                throw new IOException($"Hard link {link} was not created.", Marshal.GetLastWin32Error());
            }
            created++;
        }
        Console.WriteLine($"Bucket layout: {created} new hard links ({watch.Elapsed.TotalSeconds:F1} s).");
    }

    private static (long Count, long Bytes, long Allocated) Measure(string root)
    {
        long count = 0, bytes = 0, allocated = 0;
        var buckets = PerfManifest.BucketsDirectory(root);
        foreach (var file in new DirectoryInfo(root).EnumerateFiles("*", SearchOption.AllDirectories))
        {
            // Hard links of the bucket layout do not take space of their own.
            if (file.FullName.StartsWith(buckets, StringComparison.OrdinalIgnoreCase)) continue;
            count++;
            bytes += file.Length;
            allocated += (file.Length + 4095) / 4096 * 4096;
        }
        return (count, bytes, allocated);
    }

    [DllImport("kernel32.dll", EntryPoint = "CreateHardLinkW", SetLastError = true, CharSet = CharSet.Unicode)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool CreateHardLink(string fileName, string existingFileName, IntPtr securityAttributes);
}
