"""Скорость обучения, разогрев и число процессов загрузки данных (с причинами выбора)."""
from __future__ import annotations

import os

# ЗАМЕР (датасет на 54 класса): при батче 32 lr0=0.001 обучает
# классификатор. С optimizer="auto" ultralytics сам брал AdamW с
# lr = 0.002*5/(4+nc) = 0.00017 — в шесть раз меньше рабочего: box_loss падал
# с 1.74 до 0.27, а голова классификации не двигалась и выдавала 0.004 даже
# на обучающих картинках. Это единственная замеренная точка, остальное
# считается от неё.
LR_REF = 0.001
LR_REF_BATCH = 32

# Потолок разогрева — доля всего прогона: на коротком прогоне умножение на
# batch/32 отдало бы разогреву всё обучение.
WARMUP_MAX_SHARE = 0.25


def recommended_lr0(batch: int) -> float:
    """LR_REF * batch / LR_REF_BATCH.

    За эпоху сеть делает images/batch шагов. Батч 256 вместо 32 — в восемь
    раз меньше шагов, и при том же lr первая эпоха выглядит провалом.
    Линейное правило возвращает тот же суммарный сдвиг весов за эпоху.
    Округление до 6 знаков — иначе в паспорт попадает 0.0030000000000000005.
    """
    b = max(1, int(batch))
    return round(LR_REF * b / LR_REF_BATCH, 6)


def warmup_epochs_for(epochs: int, batch: int) -> float:
    """Разогрев в ЭПОХАХ такой, чтобы в ШАГАХ он не зависел от батча.

    Ultralytics отмеряет разогрев эпохами, а шагов в эпохе images/batch:
    «3 эпохи» при крупном батче — сотня шагов, и lr прыгает к рабочему
    раньше, чем свежая голова классификации оживёт. База длиннее
    стандартных 3 эпох на длинных прогонах: на бедных классах короткий
    разогрев загонял классификатор в нули. Потолок — WARMUP_MAX_SHARE
    прогона, но не меньше одной эпохи.
    """
    epochs = max(1, int(epochs))
    base = max(1.0, min(5.0, epochs / 10))
    scaled = base * max(1, int(batch)) / LR_REF_BATCH
    return round(min(scaled, max(1.0, epochs * WARMUP_MAX_SHARE)), 2)


def default_patience(epochs: int) -> int:
    """Ранняя остановка: не раньше 10 эпох без улучшения и не позже 40."""
    return max(10, min(40, int(epochs)))


def dataloader_workers() -> int:
    """Число процессов загрузки данных.

    ЗАМЕР: на Windows дочерние процессы создаются через
    spawn, и torch пересылает им датасет целиком — вместе с кэшем картинок
    в памяти. На 1500 кадрах это полгигабайта в pipe и падение
    «OSError: [Errno 22] Invalid argument». Поэтому на Windows загрузка
    идёт в главном процессе (workers=0).
    """
    if os.name == "nt":
        return 0
    return min(4, os.cpu_count() or 1)
